#!/bin/bash
# bm-ubuntu-grub.sh - put Googlebook OS into Ubuntu's own GRUB menu so the USB stick is NOT needed to boot it.
# Android itself already lives on the SSD; the stick only held the kernel, the ramdisk and a boot menu. This copies
# those two files (about 60 MB) into Ubuntu's /boot/gbos and adds the same menu entries to Ubuntu's GRUB.
# Needs the stick plugged in ONE last time (to copy from). Re-run it (stick plugged in) after every  sudo bash scripts/bm-boot.sh
# Run:  cd ~/gbos && sudo bash scripts/bm-ubuntu-grub.sh      Undo:  sudo rm -rf /boot/gbos /etc/grub.d/40_googlebook && sudo update-grub
set -euo pipefail
[ "$EUID" -eq 0 ] || { echo "Run with sudo:  sudo bash $0"; exit 1; }
ESPDEV=$(blkid -L GBOS-ESP || true); [ -b "${ESPDEV:-}" ] || { echo "Plug the stick in (GBOS-ESP not found)."; exit 1; }
M=$(mktemp -d); mount -o ro "$ESPDEV" "$M"; trap 'umount "$M" 2>/dev/null; rmdir "$M"' EXIT
[ -s "$M/gbos/kernel" ] && [ -s "$M/gbos/initrd.img" ] && [ -s "$M/boot/grub/grub.cfg" ] || { echo "stick has no Googlebook files - run bm-boot.sh first"; exit 1; }
mkdir -p /boot/gbos
cp "$M/gbos/kernel" /boot/gbos/kernel.new && cp "$M/gbos/initrd.img" /boot/gbos/initrd.img.new
cmp -s "$M/gbos/kernel" /boot/gbos/kernel.new && cmp -s "$M/gbos/initrd.img" /boot/gbos/initrd.img.new || { echo "copy check failed"; rm -f /boot/gbos/*.new; exit 1; }
mv /boot/gbos/kernel.new /boot/gbos/kernel; mv /boot/gbos/initrd.img.new /boot/gbos/initrd.img
# turn the stick's menu entries into a GRUB script for Ubuntu
python3 - "$M/boot/grub/grub.cfg" <<'PY'
import re, sys
cfg = open(sys.argv[1]).read()
ents = re.findall(r'menuentry "([^"]+)" \{(.*?)\n\}', cfg, re.S)
out = ['#!/bin/sh', '# generated by bm-ubuntu-grub.sh - do not edit by hand']
out.append('GB=$(grub-mkrelpath /boot/gbos)')
out.append('')
def entry(title, args, ind=''):
    return (f'{ind}menuentry "{title}" --class android --class os {{\n'
            f'{ind}    insmod part_gpt\n{ind}    insmod ext2\n'
            f'{ind}    search --no-floppy --file --set=root GBPATH/kernel\n'
            f'{ind}    linux GBPATH/kernel {args}\n{ind}    initrd GBPATH/initrd.img\n{ind}}}\n')
parsed = []
for title, body in ents:
    m = re.search(r'linux /gbos/kernel (.*)', body)
    if m: parsed.append((title, m.group(1).strip()))
main = [p for p in parsed if 'audit off' in p[0]] or parsed[:1]
rest = [p for p in parsed if p not in main]
# the script is shell: emit the entries through a here-doc so $GB expands
body = ''.join(entry(t, a) for t, a in main)
if rest:
    body += 'submenu "Googlebook OS - other options" {\n' + ''.join(entry(t, a, '  ') for t, a in rest) + '}\n'
body = body.replace('GBPATH', '$GB')
out.append("cat <<GRUBEOF\n" + body + "GRUBEOF")
open('/etc/grub.d/40_googlebook', 'w').write('\n'.join(out) + '\n')
PY
chmod +x /etc/grub.d/40_googlebook
update-grub 2>&1 | tail -6
echo; grep -c "Googlebook" /boot/grub/grub.cfg | sed 's/^/Googlebook entries in Ubuntu GRUB: /'
echo "DONE. Reboot WITHOUT the stick and look for 'Googlebook OS' in the Ubuntu GRUB menu (hold Shift or Esc at start if the menu is hidden)."
