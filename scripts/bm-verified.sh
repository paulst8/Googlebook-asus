#!/bin/bash
# bm-verified.sh - add a SECOND Googlebook OS entry to Ubuntu's boot menu: "verified boot (testing)".
# Stage 4 of the verified-boot plan. Run it AFTER  sudo bash scripts/bm-sign.sh  (and after every re-run of bm-vendor.sh + bm-sign.sh).
# It copies the boot settings Ubuntu already uses (/boot/gbos/initrd.img), and adds what a real bootloader would pass to Android:
# the fingerprint (digest) of the signed vbmeta_a that is on the SSD, its size, and the dm-verity mode "enforcing".
# The boot state label stays orange/unlocked on purpose (nothing before Android checks anything yet - see README), and
# your normal entry is NOT changed, so you can always fall back to it.
# Run:    cd ~/gbos && sudo bash scripts/bm-verified.sh          Undo:  sudo rm /etc/grub.d/41_googlebook_verified /boot/gbos/initrd-verified.img && sudo update-grub
set -euo pipefail
GBOS=${GBOS:-$PWD}; cd "$GBOS"
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd); LIB="$HERE/lib"
[ -f "$GBOS/bm.conf" ] && . "$GBOS/bm.conf"
DRYRUN=${DRYRUN:-}
GB=${GB_DIR:-/boot/gbos}
[ -z "$DRYRUN" ] && { [ "$EUID" -eq 0 ] || { echo "Run with sudo:  sudo bash $0"; exit 1; }; }
[ -s "$GB/initrd.img" ] && [ -s "$GB/kernel" ] || { echo "No Googlebook boot files in $GB - run bm-ubuntu-grub.sh first"; exit 1; }

# ---- the signed vbmeta_a that is really on the SSD (so the numbers always match what Android will read)
if [ -n "${VBMETA_IMG:-}" ]; then VB="$VBMETA_IMG"; else VB=$( { blkid -t PARTLABEL=vbmeta_a -o device | grep nvme; blkid -t PARTLABEL=vbmeta_a -o device; } | head -1 ); fi
[ -n "$VB" ] || { echo "vbmeta_a partition not found"; exit 1; }
PUB=$(python3 "$LIB/avbtool.py" info_image --image "$VB" | sed -n 's/^Public key (sha1): *//p')
FLG=$(python3 "$LIB/avbtool.py" info_image --image "$VB" | sed -n 's/^Flags: *//p' | head -1)
[ "$FLG" = "0" ] || { echo "vbmeta_a has flags=$FLG (verification still disabled) - run  sudo bash scripts/bm-sign.sh  first"; exit 1; }
[ "$PUB" != "76b0c125b33c7757e0695f02e820553890f57585" ] || { echo "vbmeta_a is still signed by Google, not by your key - run  sudo bash scripts/bm-sign.sh  first"; exit 1; }
DIG=$(python3 "$LIB/avbtool.py" calculate_vbmeta_digest --image "$VB" --hash_algorithm sha256)
SZ=$(python3 - "$VB" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read(256)
print(256 + struct.unpack('>Q', d[12:20])[0] + struct.unpack('>Q', d[20:28])[0])
PY
)
echo "vbmeta_a on the SSD: your key $PUB, digest $DIG, size $SZ"

# ---- new ramdisk file = the current one with its boot settings (bootconfig) extended
OUTF=${OUT_INITRD:-$GB/initrd-verified.img}
python3 -I - "$GB/initrd.img" "$OUTF.new" "$DIG" "$SZ" <<'PY'
import struct, sys
src, dst, dig, sz = sys.argv[1:]
d = open(src, 'rb').read()
assert d.endswith(b'#BOOTCONFIG\n'), 'no bootconfig at the end of the ramdisk'
size, csum = struct.unpack('<II', d[-20:-12])
cfg = d[-20 - size:-20]; head = d[:-20 - size]
assert sum(cfg) & 0xffffffff == csum, 'bootconfig checksum does not match'
lines = [l for l in cfg.rstrip(b'\0').decode().split('\n') if l.strip()]
drop = ('androidboot.vbmeta.digest', 'androidboot.vbmeta.size', 'androidboot.vbmeta.hash_alg', 'androidboot.vbmeta.avb_version', 'androidboot.veritymode')
lines = [l for l in lines if not l.startswith(drop)]
lines += [f'androidboot.vbmeta.digest={dig}', f'androidboot.vbmeta.size={sz}', 'androidboot.vbmeta.hash_alg=sha256',
          'androidboot.vbmeta.avb_version=1.4', 'androidboot.veritymode=enforcing']
c = ('\n'.join(lines) + '\n').encode(); c += b'\0' * (-len(c) % 4)
open(dst, 'wb').write(head + c + struct.pack('<II', len(c), sum(c) & 0xffffffff) + b'#BOOTCONFIG\n')
print('  boot settings now:'); [print('   ', l) for l in lines]
PY
mv "$OUTF.new" "$OUTF"
[ -n "$DRYRUN" ] && { echo "DRY RUN finished: $OUTF"; exit 0; }

# ---- add the menu entry: same kernel and options as the normal "audit off" entry, but the new ramdisk
ARGS=$(sed -n 's#^ *linux \$GB/kernel \(.*\)$#\1#p' /etc/grub.d/40_googlebook | grep audit=0 | head -1)
[ -n "$ARGS" ] || { echo "could not find the normal entry's kernel options in /etc/grub.d/40_googlebook"; exit 1; }
cat > /etc/grub.d/41_googlebook_verified <<GRUBS
#!/bin/sh
# generated by bm-verified.sh - do not edit by hand
GB=\$(grub-mkrelpath /boot/gbos)
cat <<GRUBEOF
menuentry "Googlebook OS - verified boot (testing)" --class android --class os {
    insmod part_gpt
    insmod ext2
    search --no-floppy --file --set=root \$GB/kernel
    linux \$GB/kernel $ARGS
    initrd \$GB/initrd-verified.img
}
GRUBEOF
GRUBS
chmod +x /etc/grub.d/41_googlebook_verified
update-grub 2>&1 | tail -4
echo "DONE. Reboot and pick 'Googlebook OS - verified boot (testing)' in Ubuntu's boot menu (your normal entry is unchanged)."
echo "Check afterwards (adb):  adb shell \"getprop | grep -iE 'vbmeta|verity'\"   - ro.boot.vbmeta.digest should equal $DIG"
