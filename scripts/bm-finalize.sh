#!/bin/bash
# bm-finalize.sh - tidy Ubuntu's boot menu for Googlebook OS and make the LOCKED entry the default.
# What it does (run it in Ubuntu, after bm-locked-test.sh has created /boot/gbos/initrd-locked.img):
#   1. one clean menu:  "Googlebook OS" (locked, the entry that works with your current data)
#                       + a submenu "Googlebook OS - other options" (unlocked / verified-only / kernel messages)
#   2. removes the separate test entries (41_googlebook_verified, 42_googlebook_locked) and leftover files in /boot/gbos
#   3. does NOT touch your default boot entry or menu time (Ubuntu/Windows menu stays as it is).
#      Only if you WANT Googlebook OS to start by itself: MAKE_DEFAULT=1 ; shorter menu time: GRUB_TIMEOUT=3
# It writes NOTHING to the Android disk, so your Android data is untouched.
# Run:   cd ~/gbos && sudo bash scripts/bm-finalize.sh          Safe to run again.
# Undo the default:  sudo cp /etc/default/grub.bak-gbos /etc/default/grub && sudo update-grub
set -euo pipefail
GB=${GB_DIR:-/boot/gbos}
GRUBD=${GRUBD_DIR:-/etc/grub.d}
DEF=${DEFAULT_FILE:-/etc/default/grub}
DRYRUN=${DRYRUN:-}
[ -n "$DRYRUN" ] || [ "$EUID" -eq 0 ] || { echo "Run with sudo:  sudo bash $0"; exit 1; }
for f in kernel initrd.img initrd-locked.img; do
  [ -s "$GB/$f" ] || { echo "$GB/$f is missing. Run  sudo bash scripts/bm-locked-test.sh  first."; exit 1; }
done

# ---- 1. kernel options: take them from the existing menu (saved once, so re-running is safe)
OLD=$GRUBD/40_googlebook
if [ ! -s "$GB/cmdline-main" ]; then
  [ -s "$OLD" ] || { echo "$OLD not found - run bm-ubuntu-grub.sh first"; exit 1; }
  LINES=$(sed -n 's#^ *linux \$GB/kernel \(.*\)$#\1#p' "$OLD")
  MAIN=$(grep -- 'audit=0' <<<"$LINES" | grep -v earlycon | head -1 || true)
  LOUD=$(grep -- 'earlycon=efifb' <<<"$LINES" | head -1 || true)
  [ -n "$MAIN" ] || MAIN=$(head -1 <<<"$LINES")
  [ -n "$MAIN" ] || { echo "could not read the kernel options from $OLD"; exit 1; }
  echo "$MAIN" > "$GB/cmdline-main"; [ -n "$LOUD" ] && echo "$LOUD" > "$GB/cmdline-loud" || true
fi
MAIN=$(cat "$GB/cmdline-main"); LOUD=$(cat "$GB/cmdline-loud" 2>/dev/null || echo "$MAIN")
echo "kernel options: $MAIN"

# ---- 2. one clean menu script
ent() { # title initrd args indent
  printf '%smenuentry "%s" --class android --class os {\n%s    insmod part_gpt\n%s    insmod ext2\n' "$4" "$1" "$4" "$4"
  printf '%s    search --no-floppy --file --set=root $GB/kernel\n%s    linux $GB/kernel %s\n%s    initrd $GB/%s\n%s}\n' "$4" "$4" "$3" "$4" "$2" "$4"
}
{
  echo '#!/bin/sh'
  echo '# generated by bm-finalize.sh - do not edit by hand'
  echo 'GB=$(grub-mkrelpath /boot/gbos)'
  echo 'cat <<GRUBEOF'
  ent "Googlebook OS" initrd-locked.img "$MAIN" ""
  echo 'submenu "Googlebook OS - other options" {'
  ent "Locked, kernel messages on screen (for troubleshooting)" initrd-locked.img "$LOUD" "  "
  ent "UNLOCKED (orange) - needs a data reset to switch (sudo bash scripts/bm-reset-data.sh)" initrd.img "$MAIN" "  "
  [ -s "$GB/initrd-verified.img" ] && ent "Verified boot but unlocked - needs a data reset to switch" initrd-verified.img "$MAIN" "  "
  echo '}'
  echo 'GRUBEOF'
} > "$OLD.new"
mv "$OLD.new" "$OLD"; chmod +x "$OLD"
rm -f "$GRUBD/41_googlebook_verified" "$GRUBD/42_googlebook_locked"

# ---- 3. clean /boot/gbos: keep only what the menu uses
KEEP=" kernel initrd.img initrd-locked.img initrd-verified.img cmdline-main cmdline-loud "
for f in "$GB"/*; do
  b=$(basename "$f")
  case "$KEEP" in *" $b "*) ;; *) echo "removing unused $b ($(du -h "$f" | cut -f1))"; rm -rf "$f";; esac
done

# ---- 4. default entry (+ optional menu time)
if [ "${MAKE_DEFAULT:-0}" = 1 ] && [ -f "$DEF" ]; then
  [ -f "$DEF.bak-gbos" ] || cp "$DEF" "$DEF.bak-gbos"
  if grep -q '^GRUB_DEFAULT=' "$DEF"; then sed -i 's|^GRUB_DEFAULT=.*|GRUB_DEFAULT="Googlebook OS"|' "$DEF"; else echo 'GRUB_DEFAULT="Googlebook OS"' >> "$DEF"; fi
fi
if [ -n "${GRUB_TIMEOUT:-}" ] && [ -f "$DEF" ]; then
  [ -f "$DEF.bak-gbos" ] || cp "$DEF" "$DEF.bak-gbos"
  sed -i "s|^GRUB_TIMEOUT=.*|GRUB_TIMEOUT=$GRUB_TIMEOUT|" "$DEF"
fi
[ -n "$DRYRUN" ] && { echo "DRY RUN finished"; exit 0; }
update-grub 2>&1 | tail -6
echo; echo "Menu entries now:"; grep -E '^(menuentry|submenu)|^\s+menuentry' /boot/grub/grub.cfg | grep -i googlebook | sed 's/ --class.*//; s/^/  /'
echo "Files in $GB:"; du -h "$GB"/* | sed 's/^/  /'
df -h /boot | tail -1 | awk '{print "/boot: " $3 " used of " $2}'
echo "DONE. Reboot: your usual menu is unchanged and Googlebook OS is one clean entry in it."
